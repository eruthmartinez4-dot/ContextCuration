"""Summarize evidence/results/*/*.json into evidence/RESULTS_SUMMARY.md.

Reports, per question and configuration: status, finish reason, latency, prompt
size, the answer, and (for vector runs) which source files were retrieved compared
with the files that actually contain the answer. It also flags local runs whose
prompt likely exceeded the Ollama context window.

It does NOT score answer quality. Fill in the scoring table by hand after reading
the answers against the expected answers.
"""
from __future__ import annotations

import argparse
import json
import re
import statistics
from pathlib import Path

RETRIEVED = re.compile(r"^--- (.+?)(?:, page \d+)? \((?:text|pdf|image), chunk \d+\) ---\s*$", re.MULTILINE)


def short_source(label: str) -> str:
    # course.txt::projects/x.md -> projects/x.md
    return label.split("::", 1)[-1]


def label_for(level_dir: str, provider: str) -> str:
    model = "Phi-4 Mini (local)" if provider == "ollama" else (
        "Gemini Flash" if provider == "gemini" else provider)
    rag = "with vector DB" if level_dir.startswith("level2") else "no vector DB"
    tag = level_dir.split("-", 1)[1] if "-" in level_dir else ""
    return f"{model}, {rag}" + (f" [{tag}]" if tag else "")


def one_line(text: str, limit: int = 220) -> str:
    flat = " ".join((text or "").split())
    return flat if len(flat) <= limit else flat[:limit].rstrip() + "..."


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence", type=Path, default=Path("evidence"))
    parser.add_argument("--questions", type=Path, default=Path("eval/questions.json"))
    parser.add_argument("--out", type=Path, default=Path("evidence/RESULTS_SUMMARY.md"))
    args = parser.parse_args()

    questions = json.loads(args.questions.read_text(encoding="utf-8"))["questions"]
    results_root = args.evidence / "results"
    level_dirs = sorted(p.name for p in results_root.iterdir() if p.is_dir()) if results_root.exists() else []
    if not level_dirs:
        print(f"No results under {results_root}. Run run_comparison.py first.")
        return 1

    lines = ["# Results Summary", "",
             "Generated by `summarize_results.py` from `evidence/results/` and `evidence/logs/`. "
             "Answers are reproduced as returned by each model. Quality scores are filled in by hand.", ""]
    latency: dict[str, list[float]] = {}
    status_count: dict[str, dict[str, int]] = {}
    prompt_sizes: dict[str, list[int]] = {}
    retrieval_hits: list[tuple[int, int]] = []
    overflow_notes: list[str] = []
    score_rows: list[str] = []

    for q in questions:
        lines += [f"## {q['id']}: {q['category']}", "", f"**Question:** {q['question']}", "",
                  f"**Expected:** {q['expected']}", ""]
        rows = ["| Configuration | Status | Finish | Seconds | Prompt chars | Answer (excerpt) |",
                "| --- | --- | --- | --- | --- | --- |"]
        details = []
        for level_dir in level_dirs:
            path = results_root / level_dir / f"{q['id']}.json"
            if not path.exists():
                continue
            report = json.loads(path.read_text(encoding="utf-8"))
            chars = report.get("prompt_characters", 0)
            num_ctx = report.get("ollama_num_ctx") or 4096

            gemini_tokens = None
            for run in report.get("runs", []):
                if run.get("provider") == "gemini":
                    gemini_tokens = (run.get("usage") or {}).get("prompt_token_count")

            log = args.evidence / "logs" / level_dir / f"{q['id']}.txt"
            if level_dir.startswith("level2") and log.exists():
                retrieved = [short_source(m) for m in RETRIEVED.findall(log.read_text(encoding="utf-8"))]
                expected = set(q.get("evidence", []))
                if expected:
                    hit = len(expected & set(retrieved))
                    retrieval_hits.append((hit, len(expected)))
                    hit_text = f"{hit}/{len(expected)} expected evidence files retrieved"
                else:
                    hit_text = "no evidence expected (absent-information question)"
                details.append(f"- `{level_dir}` retrieved: {', '.join(retrieved) or 'nothing'} ({hit_text})")

            for run in report.get("runs", []):
                provider = run.get("provider", "?")
                name = label_for(level_dir, provider)
                status = run.get("status", "?")
                seconds = run.get("elapsed_seconds")
                answer = run.get("text") or run.get("error") or ""
                rows.append(f"| {name} | {status} | {run.get('finish_reason', run.get('error_type', ''))} | "
                            f"{seconds if seconds is not None else ''} | {chars:,} | "
                            f"{one_line(answer).replace('|', '/')} |")
                details.append(f"<details><summary>{name}: full answer</summary>\n\n{answer.strip()}\n\n</details>\n")
                latency.setdefault(name, []).append(seconds or 0.0)
                status_count.setdefault(name, {}).setdefault(status, 0)
                status_count[name][status] += 1
                prompt_sizes.setdefault(name, []).append(chars)
                score_rows.append(f"| {q['id']} | {name} | | | | |")
                if provider == "ollama":
                    estimate = gemini_tokens or chars // 4
                    source = "Gemini token count" if gemini_tokens else "chars/4 estimate"
                    if estimate > num_ctx:
                        overflow_notes.append(
                            f"- {q['id']} / {level_dir}: prompt about {estimate:,} tokens ({source}) "
                            f"vs Ollama num_ctx {num_ctx:,}. Local model likely did not see the full context.")
        lines += rows + [""] + details + [""]

    summary = ["## Overview", "", "| Configuration | Runs | Status counts | Median seconds | Median prompt chars |",
               "| --- | --- | --- | --- | --- |"]
    for name in sorted(latency):
        counts = ", ".join(f"{k}: {v}" for k, v in sorted(status_count[name].items()))
        summary.append(f"| {name} | {len(latency[name])} | {counts} | "
                       f"{statistics.median(latency[name]):.2f} | {int(statistics.median(prompt_sizes[name])):,} |")
    summary.append("")
    if retrieval_hits:
        got = sum(h for h, _ in retrieval_hits)
        need = sum(n for _, n in retrieval_hits)
        summary += [f"**Vector retrieval coverage:** {got}/{need} expected evidence files appeared in the "
                    f"top-k chunks ({got / need:.0%}) across questions that have expected evidence.", ""]
    if overflow_notes:
        summary += ["**Local context overflow warnings:**", "", *overflow_notes, ""]
    summary += ["Latency includes model load time; the first local run is a cold start. "
                "Token counts differ between tokenizers, so overflow warnings are approximate.", ""]

    scoring = ["## Manual scoring (fill in)", "",
               "Score each 0 (wrong/unsupported), 1 (partly), 2 (fully). "
               "Uncertainty = says so when evidence is missing or conflicting.", "",
               "| Question | Configuration | Correct | Citations support it | Appropriate uncertainty | Notes |",
               "| --- | --- | --- | --- | --- | --- |", *score_rows, ""]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines[:4] + summary + scoring + lines[4:]), encoding="utf-8")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
